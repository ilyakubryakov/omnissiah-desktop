const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const cal = vm.createContext({ Date });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../bar/CalendarLogic.js'), 'utf8').replace('.pragma library', ''), cal);
const event = (s, e, a = false, t = s) => ({ s, e, a, t });
const ids = events => Array.from(events, e => e.t);
const day = new Date(2026, 9, 30);
const allDay = event('2026-10-30T00:00:00+02:00', '2026-10-31T00:00:00+02:00', true, 'all day');
const midnightEnd = event('2026-10-29T23:00:00+02:00', '2026-10-30T00:00:00+02:00', false, 'yesterday');
const point = event('2026-10-30T09:00:00+02:00', '', false, 'point');
const ongoing = event('2026-10-30T09:00:00+02:00', '2026-10-30T10:00:00+02:00', false, 'ongoing');
const next = event('2026-10-30T10:30:00+02:00', '2026-10-30T12:00:00+02:00', false, 'next');
const invalid = event('invalid', 'invalid', false, 'invalid');
const now = Date.parse('2026-10-30T09:30:00+02:00');
assert.deepEqual(ids(cal.onDay([midnightEnd, allDay, point, invalid], day)), ['all day', 'point']);
assert.deepEqual(ids(cal.onDay([allDay], new Date(2026, 9, 31))), []);
assert.deepEqual(ids(cal.upcoming([allDay, next, midnightEnd, point, ongoing, invalid], now, 2)), ['ongoing', 'next']);
assert.equal(cal.ongoing(ongoing, Date.parse(ongoing.e)), false);
assert.equal(cal.countdown(ongoing, now), 'Now · 30 min left');
assert.equal(cal.duration(next), '1 h 30 min');
assert.equal(cal.duration(point), '');
assert.equal(cal.duration(allDay), 'All day');

const dst = event('2026-10-25T23:30:00+02:00', '2026-10-26T00:00:00+02:00');
assert.equal(cal.onDay([dst], new Date(2026, 9, 25)).length, 1);
assert.equal(cal.onDay([dst], new Date(2026, 9, 26)).length, 0);
console.log('Calendar: exclusive boundaries, point events, ongoing priority, duration and DST passed');
